-- Tables de dimensions (schéma gold), d'après le dictionnaire de données.
-- sk_* : clé technique. La ligne sk = -1 sert de valeur "Inconnu" pour les faits
-- dont la référence est absente.
-- À créer avant les faits, et dim_geographie avant dim_etablissement.

-- Calendrier, rempli par 03_dim_temps.sql
CREATE TABLE gold.dim_temps (
    sk_date        INTEGER      PRIMARY KEY,         -- AAAAMMJJ
    date           DATE         NOT NULL UNIQUE,
    jour           SMALLINT     NOT NULL CHECK (jour BETWEEN 1 AND 31),
    jour_semaine   SMALLINT     NOT NULL CHECK (jour_semaine BETWEEN 1 AND 7),  -- 1 = lundi
    libelle_jour   VARCHAR(10)  NOT NULL,
    semaine_iso    SMALLINT     NOT NULL CHECK (semaine_iso BETWEEN 1 AND 53),
    mois           SMALLINT     NOT NULL CHECK (mois BETWEEN 1 AND 12),
    libelle_mois   VARCHAR(10)  NOT NULL,
    trimestre      SMALLINT     NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    semestre       SMALLINT     NOT NULL CHECK (semestre IN (1, 2)),
    annee          SMALLINT     NOT NULL,
    est_weekend    BOOLEAN      NOT NULL
);

-- Une ligne par commune (COG INSEE)
CREATE TABLE gold.dim_geographie (
    sk_geo               INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_commune_insee   CHAR(5)      NOT NULL UNIQUE,   -- texte pour garder 0 initial et 2A/2B
    libelle_commune      VARCHAR(100),
    code_departement     VARCHAR(3)   NOT NULL,
    libelle_departement  VARCHAR(60)  NOT NULL,
    code_region          CHAR(2)      NOT NULL,
    libelle_region       VARCHAR(60)  NOT NULL
);

CREATE TABLE gold.dim_patient (
    sk_patient         INTEGER   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patient_pseudo  CHAR(64)  NOT NULL UNIQUE,        -- HMAC-SHA256
    sexe_patient       CHAR(1)   NOT NULL CHECK (sexe_patient IN ('M', 'F', 'I')),
    annee_naissance    SMALLINT  CHECK (annee_naissance BETWEEN 1880 AND 2100),
    code_departement   VARCHAR(3) CHECK (code_departement ~ '^([0-9]{2}|2A|2B|97[1-6])$')  -- département de résidence
);

CREATE TABLE gold.dim_professionnel (
    sk_professionnel           INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_professionnel           VARCHAR(64)  NOT NULL UNIQUE,   -- 64 pour accepter l'identifiant pseudonymisé
    type_identifiant           VARCHAR(5),                     -- ADELI / RPPS
    civilite                   VARCHAR(8),
    categorie_professionnelle  VARCHAR(10),
    profession                 VARCHAR(50),
    code_specialite            VARCHAR(32),
    libelle_specialite         VARCHAR(60),
    fonction                   VARCHAR(50)
);

CREATE TABLE gold.dim_diagnostic (
    sk_diagnostic       INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_diag           VARCHAR(10)   NOT NULL UNIQUE,   -- CIM-10
    libelle_diagnostic  VARCHAR(255)  NOT NULL,
    code_chapitre       VARCHAR(5),
    libelle_chapitre    VARCHAR(150)
);

-- SCD type 2 : une ligne par version de l'établissement.
-- Version en cours : date_fin_validite = 9999-12-31 et est_courant = true.
CREATE TABLE gold.dim_etablissement (
    sk_etablissement     INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organisation      VARCHAR(20)   NOT NULL,
    finess_site          CHAR(9),
    finess_juridique     CHAR(9),
    raison_sociale       VARCHAR(255)  NOT NULL,
    siret                CHAR(14),
    adresse_complete     VARCHAR(255),
    code_postal          CHAR(5),
    sk_geo               INTEGER       NOT NULL DEFAULT -1 REFERENCES gold.dim_geographie (sk_geo),
    date_debut_validite  DATE          NOT NULL,
    date_fin_validite    DATE          NOT NULL DEFAULT DATE '9999-12-31',
    est_courant          BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_etab_version UNIQUE (id_organisation, date_debut_validite),
    CONSTRAINT ck_etab_periode CHECK (date_fin_validite >= date_debut_validite),
    CONSTRAINT ck_etab_courant CHECK (est_courant = (date_fin_validite = DATE '9999-12-31')),
    CONSTRAINT ck_finess_site  CHECK (finess_site      ~ '^([0-9]{2}|2A|2B)[0-9]{7}$'),
    CONSTRAINT ck_finess_jur   CHECK (finess_juridique ~ '^([0-9]{2}|2A|2B)[0-9]{7}$'),
    CONSTRAINT ck_siret        CHECK (siret ~ '^[0-9]{14}$')
);

-- une seule version en cours par établissement
CREATE UNIQUE INDEX uq_etab_courant ON gold.dim_etablissement (id_organisation) WHERE est_courant;

