-- Tables de faits version optimisée (schéma gold).
-- fait_consultation et fait_deces sont partitionnées par année (RANGE sur la clé AAAAMMJJ).
-- fait_hospitalisation et fait_satisfaction sont trop petites pour être partitionnées.
-- La clé primaire d'une table partitionnée doit contenir la clé de partition,
-- d'où (id_consultation, sk_date) et (id_deces, sk_date_deces).

CREATE TABLE gold.fait_consultation (
    id_consultation    BIGINT       NOT NULL,
    sk_date            INTEGER      NOT NULL REFERENCES gold.dim_temps (sk_date),
    sk_patient         INTEGER      NOT NULL REFERENCES gold.dim_patient (sk_patient),
    sk_professionnel   INTEGER      NOT NULL REFERENCES gold.dim_professionnel (sk_professionnel),
    sk_diagnostic      INTEGER      NOT NULL REFERENCES gold.dim_diagnostic (sk_diagnostic),
    sk_etablissement   INTEGER      NOT NULL REFERENCES gold.dim_etablissement (sk_etablissement),
    motif              VARCHAR(50),
    age_consultation   SMALLINT     CHECK (age_consultation BETWEEN 0 AND 130),
    duree_minutes      INTEGER      CHECK (duree_minutes > 0),
    nb_prescriptions   SMALLINT     NOT NULL DEFAULT 0 CHECK (nb_prescriptions >= 0),
    nb_consultation    SMALLINT     NOT NULL DEFAULT 1 CHECK (nb_consultation = 1),
    PRIMARY KEY (id_consultation, sk_date)
) PARTITION BY RANGE (sk_date);

-- Le fichier INSEE n'a pas d'identifiant, id_deces vient d'une séquence
CREATE SEQUENCE gold.seq_fait_deces;

CREATE TABLE gold.fait_deces (
    id_deces        BIGINT    NOT NULL DEFAULT nextval('gold.seq_fait_deces'),
    sk_date_deces   INTEGER   NOT NULL REFERENCES gold.dim_temps (sk_date),
    sk_geo_deces    INTEGER   NOT NULL REFERENCES gold.dim_geographie (sk_geo),
    sexe_defunt     CHAR(1)   NOT NULL CHECK (sexe_defunt IN ('M', 'F')),
    age_deces       SMALLINT  CHECK (age_deces BETWEEN 0 AND 120),
    nb_deces        SMALLINT  NOT NULL DEFAULT 1 CHECK (nb_deces = 1),
    PRIMARY KEY (id_deces, sk_date_deces)
) PARTITION BY RANGE (sk_date_deces);

-- Crée une partition par année : <table>_AAAA couvre [AAAA0101, AAAA+1 0101)
-- Ajouter une année plus tard : CALL gold.creer_partitions_annuelles('fait_consultation', 2031, 2031);
CREATE OR REPLACE PROCEDURE gold.creer_partitions_annuelles(p_table TEXT, p_annee_debut INT, p_annee_fin INT)
LANGUAGE plpgsql AS $$
DECLARE
    a INT;
BEGIN
    FOR a IN p_annee_debut .. p_annee_fin LOOP
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS gold.%I PARTITION OF gold.%I FOR VALUES FROM (%s) TO (%s)',
            p_table || '_' || a, p_table, a * 10000 + 101, (a + 1) * 10000 + 101);
    END LOOP;
END $$;

CALL gold.creer_partitions_annuelles('fait_consultation', 2010, 2030);
CALL gold.creer_partitions_annuelles('fait_deces', 1970, 2030);

-- Partitions par défaut pour les dates hors plage (dont -1)
CREATE TABLE gold.fait_consultation_defaut PARTITION OF gold.fait_consultation DEFAULT;
CREATE TABLE gold.fait_deces_defaut        PARTITION OF gold.fait_deces        DEFAULT;

-- Tables non partitionnées : même structure que gold_v0 (LIKE ne copie pas les FK)
CREATE TABLE gold.fait_hospitalisation (LIKE gold_v0.fait_hospitalisation INCLUDING ALL);
ALTER TABLE gold.fait_hospitalisation
    ADD FOREIGN KEY (sk_date_entree)   REFERENCES gold.dim_temps (sk_date),
    ADD FOREIGN KEY (sk_date_sortie)   REFERENCES gold.dim_temps (sk_date),
    ADD FOREIGN KEY (sk_patient)       REFERENCES gold.dim_patient (sk_patient),
    ADD FOREIGN KEY (sk_diagnostic)    REFERENCES gold.dim_diagnostic (sk_diagnostic),
    ADD FOREIGN KEY (sk_etablissement) REFERENCES gold.dim_etablissement (sk_etablissement);

CREATE TABLE gold.fait_satisfaction (LIKE gold_v0.fait_satisfaction INCLUDING ALL);
ALTER TABLE gold.fait_satisfaction
    ALTER COLUMN id_satisfaction ADD GENERATED BY DEFAULT AS IDENTITY,
    ADD FOREIGN KEY (sk_date)          REFERENCES gold.dim_temps (sk_date),
    ADD FOREIGN KEY (sk_etablissement) REFERENCES gold.dim_etablissement (sk_etablissement),
    -- un résultat par établissement, année et enquête (évite les doublons au rechargement)
    ADD CONSTRAINT uq_satisfaction UNIQUE (sk_etablissement, sk_date, type_enquete);
